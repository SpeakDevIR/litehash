        function toggleMobileMenu() {
            var menu = document.getElementById('mobile-menu');
            var icon = document.getElementById('mobile-icon');
            var btn = document.getElementById('mobile-btn');
            
            if (menu.classList.contains('hidden')) {
                // OPEN MENU
                menu.classList.remove('hidden');
                
                // Icon Change to X
                icon.classList.remove('fa-bars');
                icon.classList.add('fa-times');
                btn.classList.add('bg-white/30', 'border-white/50');
            } else {
                // CLOSE MENU
                menu.classList.add('hidden');
                
                // Icon Change to Hamburger
                icon.classList.remove('fa-times');
                icon.classList.add('fa-bars');
                btn.classList.remove('bg-white/30', 'border-white/50');
            }
        }
