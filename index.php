                            requestAnimationFrame(updateCount); // Smoother than setTimeout
                        } else {
                            if(isFloat) {
                                el.innerText = target.toFixed(4);
                            } else {
                                el.innerText = Math.ceil(target).toLocaleString();
                            }
                        }
                    };
                    updateCount();
                };

                // Jab section screen par aaye tabhi animation start hogi
                const observer = new IntersectionObserver((entries) => {
                    if (entries[0].isIntersecting) {
                        counters.forEach(c => animateCounter(c, false));
                        floatCounters.forEach(c => animateCounter(c, true));
                        observer.disconnect(); 
                    }
                }, { threshold: 0.3 });

